/**
 * Контент страницы «О компании».
 */

function site_about_team_image_path(): string
{
    return '/assets/about/team-office.png';
}

function site_about_team_image_exists(): bool
{
    return is_readable(dirname(__DIR__) . site_about_team_image_path());
}

/**
 * @return list<array{value: string, label: string}>
 */
function site_about_stats(): array
{
    $rating = number_format((float) site_env('SITE_REVIEWS_RATING', '4.9'), 1, '.', '');
    $reviewsCount = (int) site_env('SITE_REVIEWS_COUNT', '250');
    $reviewsLabel = $reviewsCount > 0
        ? number_format($reviewsCount, 0, '.', ' ') . '+ отзывов'
        : 'отзывы клиентов';

    return [
        [
            'value' => (string) (int) SITE_FOUNDED_YEAR,
            'label' => 'на рынке с',
        ],
        [
            'value' => $rating,
            'label' => 'средняя оценка',
        ],
        [
            'value' => SITE_CITY_TAG,
            'label' => 'работаем в городе',
        ],
        [
            'value' => $reviewsLabel,
            'label' => 'на площадках',
        ],
    ];
}

